/**
 * Key layouts transcribed from the Arbiter web configurator's matrices (see
 * docs/arbiter-support.md). Key codes are the .NET `Keys` values the vendor uses;
 * each matrix entry is `[name, keyCode, line]` where `line` is the keyboard row.
 */

export type ArbiterLayoutId = "yl" | "s2" | "i2" | "u2";

export interface ArbiterMatrixKey {
  name: string;
  keyCode: number;
  /** Physical row, 0 at the top. */
  line: number;
}

export interface ArbiterLayout {
  /** The vendor's key matrix in matrix order. Some entries are placeholders (`None`) that are not on the wire. */
  matrix: readonly ArbiterMatrixKey[];
  /** Factory key codes per layer, in matrix order. Layer 1 is the FN layer on the PRO models. */
  layers: readonly (readonly number[])[];
}

type Row = readonly [string, number, number];
const matrix = (rows: readonly Row[]): ArbiterMatrixKey[] => rows.map(([name, keyCode, line]) => ({ name, keyCode, line }));

